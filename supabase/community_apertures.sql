-- 启慧研习院 · 公共衍射屏
-- 在 Supabase Dashboard > SQL Editor 中整段执行。
-- 表只允许 service_role / secret key 访问；浏览器必须通过 EdgeOne Functions API。

create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;
create schema if not exists private;

-- 在数据库内生成一次长期稳定的 IP 摘要盐。即使以后轮换 Supabase Secret Key，
-- 用户仍能管理原来的三个档位。原始 IP 只在 TLS 请求和函数执行期间存在，不写入表。
create table if not exists private.community_settings (
  singleton boolean primary key default true check (singleton),
  ip_hash_salt bytea not null
);

insert into private.community_settings (singleton, ip_hash_salt)
values (true, extensions.gen_random_bytes(32))
on conflict (singleton) do nothing;

create or replace function public.community_owner_hash(client_ip text)
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select pg_catalog.encode(
    extensions.hmac(
      pg_catalog.convert_to(pg_catalog.btrim(client_ip), 'UTF8'),
      settings.ip_hash_salt,
      'sha256'
    ),
    'hex'
  )
  from private.community_settings as settings
  where settings.singleton = true
    and pg_catalog.char_length(pg_catalog.btrim(client_ip)) between 2 and 64;
$$;

create table if not exists public.community_apertures (
  id uuid primary key default gen_random_uuid(),
  owner_hash text not null check (char_length(owner_hash) = 64),
  slot smallint not null check (slot between 1 and 3),
  nickname varchar(20) not null check (char_length(trim(nickname)) between 1 and 20),
  pattern_name varchar(32) not null check (char_length(trim(pattern_name)) between 1 and 32),
  aperture_data jsonb not null,
  preview_data text not null,
  pattern_hash text not null check (char_length(pattern_hash) = 64),
  moderation jsonb not null default '{"method":"local-rules","status":"approved"}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint community_apertures_owner_slot_key unique (owner_hash, slot),
  constraint community_apertures_format_check check (
    aperture_data ->> 'format' = 'fraunhofer-aperture-v1'
    and (aperture_data ->> 'size')::integer = 256
    and jsonb_typeof(aperture_data -> 'amplitude') = 'string'
    and jsonb_typeof(aperture_data -> 'phase') = 'string'
  )
);

comment on table public.community_apertures is
  '公开衍射屏；owner_hash 是由 EdgeOne 服务端对真实 IP 加盐摘要后的值，不保存原始 IP。';
comment on column public.community_apertures.slot is '同一 IP 摘要只能使用 1、2、3 三个档位。';
comment on column public.community_apertures.preview_data is '由服务端从振幅数据生成的 48x48 灰度字节 Base64。';

create index if not exists community_apertures_name_order_idx
  on public.community_apertures (lower(pattern_name), id);
create index if not exists community_apertures_updated_idx
  on public.community_apertures (updated_at desc);
create index if not exists community_apertures_pattern_hash_idx
  on public.community_apertures (pattern_hash);

create table if not exists public.community_blocked_terms (
  id bigint generated by default as identity primary key,
  term text not null,
  category text not null check (category in ('pornography', 'gambling', 'drugs', 'politics')),
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  constraint community_blocked_terms_unique unique (term, category)
);

comment on table public.community_blocked_terms is
  '服务端上传审核词库；可以在 Supabase 表编辑器中继续补充。';

create index if not exists community_blocked_terms_enabled_idx
  on public.community_blocked_terms (enabled) where enabled;

-- 有限图样规则：管理员把已确认违规图样的 SHA-256 写入此表后，
-- 同哈希的现有公共数据会被触发器立即清除，后续上传也会被服务端拒绝。
create table if not exists public.community_blocked_pattern_hashes (
  pattern_hash text primary key check (char_length(pattern_hash) = 64),
  category text not null check (category in ('pornography', 'gambling', 'drugs', 'politics')),
  note text not null default '',
  created_at timestamptz not null default now()
);

create or replace function public.set_community_aperture_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists community_apertures_set_updated_at on public.community_apertures;
create trigger community_apertures_set_updated_at
before update on public.community_apertures
for each row execute function public.set_community_aperture_updated_at();

create or replace function public.purge_blocked_community_apertures()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  delete from public.community_apertures
  where pattern_hash = new.pattern_hash;
  return new;
end;
$$;

drop trigger if exists community_pattern_hash_purge on public.community_blocked_pattern_hashes;
create trigger community_pattern_hash_purge
after insert or update of pattern_hash on public.community_blocked_pattern_hashes
for each row execute function public.purge_blocked_community_apertures();

alter table public.community_apertures enable row level security;
alter table public.community_blocked_terms enable row level security;
alter table public.community_blocked_pattern_hashes enable row level security;

-- 不创建 anon/authenticated policy；即使有人拿到表名，也无法从浏览器绕过三档限制。
revoke all on schema private from public, anon, authenticated;
revoke all on table private.community_settings from public, anon, authenticated;
revoke all on table public.community_apertures from anon, authenticated;
revoke all on table public.community_blocked_terms from anon, authenticated;
revoke all on table public.community_blocked_pattern_hashes from anon, authenticated;
revoke all on sequence public.community_blocked_terms_id_seq from anon, authenticated;
revoke all on function public.community_owner_hash(text) from public, anon, authenticated;
revoke all on function public.set_community_aperture_updated_at() from public, anon, authenticated;
revoke all on function public.purge_blocked_community_apertures() from public, anon, authenticated;

grant select, insert, update, delete on table public.community_apertures to service_role;
grant select, insert, update, delete on table public.community_blocked_terms to service_role;
grant select, insert, update, delete on table public.community_blocked_pattern_hashes to service_role;
grant usage, select on sequence public.community_blocked_terms_id_seq to service_role;
grant execute on function public.community_owner_hash(text) to service_role;

